def project_polygon(polygon: List[Point],
                    screen_w: int, screen_h: int,
                    margin: int = 80) -> List[Tuple[int, int]]:
    """
    Converte coordenadas geográficas (lon, lat) para pixels na tela.
    Mantém o mapa grande e centralizado, respeitando a margem.
    """
    if not polygon:
        return []
    lons = [p[0] for p in polygon]
    lats = [p[1] for p in polygon]
    min_lon, max_lon = min(lons), max(lons)
    min_lat, max_lat = min(lats), max(lats)
    span_lon = max_lon - min_lon or 1.0
    span_lat = max_lat - min_lat or 1.0
    uw    = screen_w - 2 * margin
    uh    = screen_h - 2 * margin
    scale = min(uw / span_lon, uh / span_lat)
    ox    = margin + (uw - span_lon * scale) / 2
    oy    = margin + (uh - span_lat * scale) / 2
    return [
        (int(ox + (lon - min_lon) * scale),
         int(oy + (max_lat - lat) * scale))   # inverte Y
        for lon, lat in polygon
    ]


def point_in_polygon(px: float, py: float,
                     poly: List[Tuple[int, int]]) -> bool:
    """Ray-casting para verificar se ponto está dentro do polígono da arena."""
    n      = len(poly)
    inside = False
    j      = n - 1
    for i in range(n):
        xi, yi = poly[i]
        xj, yj = poly[j]
        if ((yi > py) != (yj > py)) and \
           (px < (xj - xi) * (py - yi) / (yj - yi + 1e-9) + xi):
            inside = not inside
        j = i
    return inside
